/**
 * Lists the sticker pack under public/stickers into lib/stickers.ts.
 *
 * Same arrangement as the wallpapers, and for the same reason: the folder is
 * the source of truth, so nobody has to remember to edit an array after
 * dropping a file in. The pack is also published on Telegram, and the two have
 * to hold the same twenty in the same order — a grid on the site that shows
 * nineteen of them is worse than no grid.
 *
 * The label comes out of the file name: `05-paste-it.png` is "paste it". That
 * is why the files are named the way they are, and it means renaming a sticker
 * is renaming one file rather than editing code and a file in step.
 *
 *     node scripts/sticker-manifest.mjs
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const DIR = join(ROOT, 'public', 'stickers');
const FULL = join(DIR, 'full');
const THUMB = join(DIR, 'thumb');
const OUT = join(ROOT, 'lib', 'stickers.ts');

const files = existsSync(FULL)
  ? readdirSync(FULL)
      .filter((n) => /\.(png|webp)$/i.test(n))
      // Numeric prefix order, which is picker order on Telegram.
      .sort()
  : [];

const rows = files.map((name) => {
  const id = name.replace(/\.[^.]+$/, '');
  return {
    id,
    label: id.replace(/^\d+-/, '').replace(/-/g, ' '),
    full: `/stickers/full/${name}`,
    thumb: existsSync(join(THUMB, name)) ? `/stickers/thumb/${name}` : `/stickers/full/${name}`,
  };
});

const body = rows
  .map(
    (r) =>
      `  { id: '${r.id}', label: '${r.label.replace(/'/g, "\\'")}', full: '${r.full}', thumb: '${r.thumb}' },`,
  )
  .join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/sticker-manifest.mjs — do not edit by hand.\n` +
    `// The pack under public/stickers/full, in numeric order, which is the\n` +
    `// order they sit in on Telegram. The label is the file name.\n\n` +
    `export type Sticker = { id: string; label: string; full: string; thumb: string };\n\n` +
    `export const STICKERS: Sticker[] = [\n${body}\n];\n\n` +
    `/** Where the pack is installed from. */\n` +
    `export const STICKER_PACK = 'https://t.me/addstickers/HollowAgent';\n`,
  'utf8',
);

console.log(`sticker-manifest: ${rows.length} stickers listed in lib/stickers.ts`);
