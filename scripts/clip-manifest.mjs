/**
 * Writes a content hash for every file under public/clips.
 *
 * The clips are served with `Cache-Control: immutable` for a year, which is
 * right for them — they are large and they rarely change. But `immutable`
 * means the browser does not revalidate at all, and the paths are stable, so
 * re-rendering a clip would never reach anyone who had already loaded the old
 * one. Worse, a copy fetched while a file was mid-write is kept just as
 * confidently: a truncated video fails to decode, and a video that cannot
 * decode is transparent rather than black, so the idle loop shows through and
 * the room looks like the hover did nothing.
 *
 * Hashing the bytes into the URL makes the address change whenever the file
 * changes, which is the thing `immutable` assumes is already true.
 *
 *     node scripts/clip-manifest.mjs
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const CLIPS = join(ROOT, 'public', 'clips');
const OUT = join(ROOT, 'lib', 'clipHashes.ts');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const files = walk(CLIPS).sort();
const entries = files.map((full) => {
  const key = relative(CLIPS, full).split(sep).join('/');
  const hash = createHash('sha1').update(readFileSync(full)).digest('hex').slice(0, 10);
  return [key, hash];
});

const body = entries.map(([k, v]) => `  '${k}': '${v}',`).join('\n');
writeFileSync(
  OUT,
  `// Generated by scripts/clip-manifest.mjs — do not edit by hand.\n` +
    `// Content hashes for everything under public/clips, so that an immutable\n` +
    `// cache entry can never outlive the file it was taken from.\n` +
    `export const CLIP_HASHES: Record<string, string> = {\n${body}\n};\n`,
  'utf8',
);

console.log(`clip-manifest: ${entries.length} files hashed into lib/clipHashes.ts`);
