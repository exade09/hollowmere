/**
 * Lists the stills of the shut places into lib/holds.ts.
 *
 * Six of the nine places are real and unfinished. Each one can carry a picture
 * of itself, and the point of this script is that hanging that picture is a
 * file copy: drop `public/holds/great-hall.jpg` in and the card on the map
 * starts opening it, with nothing in the code to change.
 *
 * The slug in the file name is the slug in HOLD. A file whose name matches no
 * place is reported rather than silently ignored — a still nobody can reach is
 * always a typo in the name, and it is easier to be told than to wonder why the
 * card is still dead.
 *
 *     node scripts/hold-manifest.mjs
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const DIR = join(ROOT, 'public', 'holds');
const OUT = join(ROOT, 'lib', 'holds.ts');

/** Kept in step with HOLD in lib/content.ts by hand: it is six lines. */
const KNOWN = [
  'great-hall',
  'hollow-wood',
  'low-quarter',
  'chapel-of-ash',
  'watchtower',
  'ossuary',
];

const files = existsSync(DIR)
  ? readdirSync(DIR).filter((n) => /\.(jpe?g|png|webp)$/i.test(n))
  : [];

const found = new Map();
for (const name of files.sort()) {
  const slug = name.replace(/\.[^.]+$/, '');
  if (!KNOWN.includes(slug)) {
    console.warn(`hold-manifest: ${name} matches no place — check the name`);
    continue;
  }
  if (!found.has(slug)) found.set(slug, `/holds/${name}`);
}

const body = [...found.entries()].map(([k, v]) => `  '${k}': '${v}',`).join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/hold-manifest.mjs — do not edit by hand.\n` +
    `// Stills of the places that are real and not finished, keyed by the slug\n` +
    `// in HOLD. A place with no entry here simply has no picture yet.\n\n` +
    `export const HOLD_STILLS: Record<string, string> = {\n${body}\n};\n`,
  'utf8',
);

console.log(
  `hold-manifest: ${found.size} of ${KNOWN.length} places have a still` +
    (found.size ? `: ${[...found.keys()].join(', ')}` : ''),
);
