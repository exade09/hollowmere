/**
 * Lists every wallpaper under public/wallpapers into lib/wallpapers.ts.
 *
 * The point is that adding one is a file copy and nothing else: drop an image
 * into public/wallpapers/full and it appears in the library the next time the
 * app builds or the dev server starts. No array to edit, so the array can
 * never disagree with the folder.
 *
 * A matching name under public/wallpapers/thumb is used for the grid when it
 * exists, and the full image stands in for itself when it does not — so a new
 * drop-in works immediately and only pays for a thumbnail once somebody runs
 * scripts/wallpaper-thumbs.py. Dimensions are read out of the file header
 * rather than assumed, because the grid reserves each tile's aspect ratio
 * before the image loads and a wrong guess makes the whole grid jump.
 *
 *     node scripts/wallpaper-manifest.mjs
 */
import { existsSync, openSync, readSync, closeSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const DIR = join(ROOT, 'public', 'wallpapers');
const FULL = join(DIR, 'full');
const THUMB = join(DIR, 'thumb');
const OUT = join(ROOT, 'lib', 'wallpapers.ts');

/** Width and height out of a JPEG's SOF marker, or a PNG's IHDR. */
function dimensions(path) {
  const fd = openSync(path, 'r');
  try {
    const head = Buffer.alloc(32);
    readSync(fd, head, 0, 32, 0);

    // PNG: the IHDR chunk is always first, at a fixed offset.
    if (head.slice(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) {
      return { w: head.readUInt32BE(16), h: head.readUInt32BE(20) };
    }

    // JPEG: walk the markers to the first start-of-frame.
    if (head[0] === 0xff && head[1] === 0xd8) {
      let pos = 2;
      const buf = Buffer.alloc(9);
      for (;;) {
        if (readSync(fd, buf, 0, 9, pos) < 9) break;
        if (buf[0] !== 0xff) {
          pos += 1;
          continue;
        }
        const marker = buf[1];
        const length = buf.readUInt16BE(2);
        // Any of the SOFn markers carries the size; the ones excluded here are
        // restart and standalone markers that carry no length at all.
        if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
          return { h: buf.readUInt16BE(5), w: buf.readUInt16BE(7) };
        }
        if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) {
          pos += 2;
          continue;
        }
        pos += 2 + length;
      }
    }
  } finally {
    closeSync(fd);
  }
  return null;
}

const files = existsSync(FULL)
  ? readdirSync(FULL)
      .filter((n) => /\.(jpe?g|png|webp)$/i.test(n))
      .sort()
  : [];

const rows = files.map((name) => {
  const size = dimensions(join(FULL, name)) || { w: 1920, h: 1080 };
  // Thumbnails are always written as jpeg whatever the original was, so both
  // spellings are checked rather than just the original's extension.
  const asJpeg = name.replace(/\.[^.]+$/, '.jpg');
  const found = [name, asJpeg].find((n) => existsSync(join(THUMB, n)));
  return {
    id: name.replace(/\.[^.]+$/, ''),
    full: `/wallpapers/full/${name}`,
    thumb: found ? `/wallpapers/thumb/${found}` : `/wallpapers/full/${name}`,
    ...size,
  };
});

const body = rows
  .map(
    (r) =>
      `  { id: '${r.id}', full: '${r.full}', thumb: '${r.thumb}', w: ${r.w}, h: ${r.h} },`,
  )
  .join('\n');

writeFileSync(
  OUT,
  `// Generated by scripts/wallpaper-manifest.mjs — do not edit by hand.\n` +
    `// Everything under public/wallpapers/full, in name order. Adding a\n` +
    `// wallpaper is a file copy: this list is rebuilt on every dev start and\n` +
    `// every build, so it cannot disagree with the folder.\n\n` +
    `export type Wallpaper = {\n` +
    `  id: string;\n` +
    `  /** Full-size image, what a click opens and what a save writes. */\n` +
    `  full: string;\n` +
    `  /** Grid image. Falls back to the full one when no thumbnail exists. */\n` +
    `  thumb: string;\n` +
    `  w: number;\n` +
    `  h: number;\n` +
    `};\n\n` +
    `export const WALLPAPERS: Wallpaper[] = [\n${body}\n];\n`,
  'utf8',
);

console.log(`wallpaper-manifest: ${rows.length} wallpapers listed in lib/wallpapers.ts`);
